using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Nerosoft.Euonia.Endpoint.SourceGenerator;

/// <summary>
/// 为 <c>ExposeGrpcAttribute</c> 生成 protobuf-net.Grpc 契约与适配器。
/// </summary>
[Generator]
public sealed class GrpcGenerator : IIncrementalGenerator
{
	private const string AttributeName = "Nerosoft.Euonia.Endpoint.ExposeGrpcAttribute";

	private static readonly DiagnosticDescriptor _methodKindMismatch = new(
		"EUONIA001",
		"gRPC method type mismatch",
		"The GrpcMethod value on '{0}' does not match its streaming signature",
		"Euonia.Endpoint",
		DiagnosticSeverity.Warning,
		isEnabledByDefault: true);

	private static readonly DiagnosticDescriptor _serviceNameConflict = new(
		"EUONIA002",
		"gRPC service name conflict",
		"Multiple contracts use the same gRPC service name '{0}'",
		"Euonia.Endpoint",
		DiagnosticSeverity.Warning,
		isEnabledByDefault: true);

	/// <inheritdoc/>
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var methods = context.SyntaxProvider.ForAttributeWithMetadataName(
				AttributeName,
				static (node, _) => node is MethodDeclarationSyntax,
				static (ctx, _) => (IMethodSymbol)ctx.TargetSymbol)
			.Where(static method => method.ContainingType is { TypeKind: TypeKind.Interface })
			.Collect()
			.Combine(context.CompilationProvider);

		context.RegisterSourceOutput(methods, static (production, source) =>
			Execute(production, source.Left, source.Right));
	}

	private static void Execute(SourceProductionContext context, ImmutableArray<IMethodSymbol> methods, Compilation compilation)
	{
		if (!compilation.ReferencedAssemblyNames.Any(assembly => assembly.Name == "Euonia.Endpoint.Grpc"))
		{
			return;
		}

		if (methods.IsDefaultOrEmpty)
		{
			return;
		}

		var builder = new StringBuilder();
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine("using System;");
		builder.AppendLine("using System.Collections.Generic;");
		builder.AppendLine("using System.Threading.Tasks;");
		builder.AppendLine("using Microsoft.AspNetCore.Builder;");
		builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
		builder.AppendLine("using Microsoft.Extensions.Logging;");
		builder.AppendLine("using Microsoft.Extensions.Options;");
		builder.AppendLine("using ProtoBuf.Grpc;");
		builder.AppendLine("using ProtoBuf.Grpc.Configuration;");
		builder.AppendLine();
		builder.AppendLine("[assembly: global::Nerosoft.Euonia.Endpoint.Grpc.GrpcGeneratedMapping(typeof(global::Nerosoft.Euonia.Endpoint.Generated.GrpcMappings))]");
		builder.AppendLine();
		builder.AppendLine("namespace Nerosoft.Euonia.Endpoint.Generated;");
		builder.AppendLine();

		var contracts = new List<(string Contract, string Adapter, string ServiceName, string ServiceType)>();
		var serviceNames = new HashSet<string>(StringComparer.Ordinal);
		var index = 0;

		foreach (var group in methods.GroupBy(method => method.ContainingType, SymbolEqualityComparer.Default))
		{
			var serviceType = (INamedTypeSymbol)group.Key!;
			var entries = new List<Entry>();
			foreach (var method in group)
			{
				foreach (var attribute in method.GetAttributes().Where(IsExposeGrpcAttribute))
				{
					var prefix = GetString(attribute, "Prefix");
					var route = GetString(attribute, "Route");
					entries.Add(new Entry(method, prefix, string.IsNullOrWhiteSpace(route) ? GetDefaultMethodName(method) : route, GetMethodKind(attribute)));
				}
			}

			foreach (var prefixGroup in entries.GroupBy(entry => entry.Prefix, StringComparer.Ordinal))
			{
				var baseName = serviceType.Name;
				if (baseName.Length > 1 && baseName[0] == 'I' && char.IsUpper(baseName[1]))
				{
					baseName = baseName.Substring(1);
				}
				var contractName = "I" + Sanitize(baseName) + "GrpcContract" + index;
				var adapterName = Sanitize(baseName) + "GrpcAdapter" + index;
				var serviceName = string.IsNullOrWhiteSpace(prefixGroup.Key) ? GetDefaultServiceName(serviceType) : prefixGroup.Key;
				if (!serviceNames.Add(serviceName))
				{
					context.ReportDiagnostic(Diagnostic.Create(_serviceNameConflict, serviceType.Locations.FirstOrDefault(), serviceName));
					continue;
				}

				index++;

				var plans = new List<MethodPlan>();
				var seenRoutes = new HashSet<string>(StringComparer.Ordinal);
				foreach (var entry in prefixGroup)
				{
					if (!seenRoutes.Add(entry.Route))
					{
						continue;
					}

					if (!IsMethodKindCompatible(entry))
					{
						context.ReportDiagnostic(Diagnostic.Create(_methodKindMismatch, entry.Method.Locations.FirstOrDefault(), entry.Method.Name));
						continue;
					}

					var plan = BuildPlan(serviceType, entry, contractName);
					if (plan != null)
					{
						plans.Add(plan);
					}
				}

				if (plans.Count == 0)
				{
					continue;
				}

				EmitContract(builder, serviceType, contractName, adapterName, serviceName, plans);
				contracts.Add((contractName, adapterName, serviceName, serviceType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)));
			}
		}

		if (contracts.Count == 0)
		{
			return;
		}

		EmitRegistration(builder, contracts);
		context.AddSource("GrpcGenerated.g.cs", builder.ToString());
	}

	private static void EmitContract(StringBuilder builder, INamedTypeSymbol serviceType, string contractName, string adapterName, string serviceName, List<MethodPlan> plans)
	{
		foreach (var plan in plans)
		{
			if (plan.RequestWrapperName == null)
			{
				continue;
			}

			builder.AppendLine("[global::System.Runtime.Serialization.DataContract]");
			builder.AppendLine("public sealed class " + plan.RequestWrapperName);
			builder.AppendLine("{");
			for (var i = 0; i < plan.RequestParameters.Count; i++)
			{
				var parameter = plan.RequestParameters[i];
				builder.AppendLine("	[global::System.Runtime.Serialization.DataMember(Order = " + (i + 1) + ")]");
				builder.AppendLine("	public " + parameter.Type + " " + parameter.PropertyName + " { get; set; } = default!;");
			}
			builder.AppendLine("}");
			builder.AppendLine();
		}

		builder.AppendLine("[global::ProtoBuf.Grpc.Configuration.Service(" + Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(serviceName, quote: true) + ")]");
		builder.AppendLine("public interface " + contractName);
		builder.AppendLine("{");
		foreach (var plan in plans)
		{
			builder.AppendLine("	[global::ProtoBuf.Grpc.Configuration.Operation(" + Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(plan.Route, quote: true) + ")]");
			builder.AppendLine("	" + plan.ContractReturnType + " " + plan.ContractMethodName + "(" + plan.ContractParameter + ");");
		}
		builder.AppendLine("}");
		builder.AppendLine();

		builder.AppendLine("public sealed class " + adapterName + " : " + contractName);
		builder.AppendLine("{");
		builder.AppendLine("	private readonly " + serviceType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + " _service;");
		builder.AppendLine("	public " + adapterName + "(" + serviceType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + " service) { _service = service; }");
		foreach (var plan in plans)
		{
			EmitAdapterMethod(builder, plan);
		}
		builder.AppendLine("}");
		builder.AppendLine();
	}

	private static void EmitAdapterMethod(StringBuilder builder, MethodPlan plan)
	{
		var method = plan.Method;
		var arguments = new List<string>();
		if (plan.RequestIsStream)
		{
			arguments.Add("request");
		}
		else if (plan.RequestParameters.Count == 0)
		{
			// no request arguments
		}
		else
		{
			foreach (var parameter in plan.RequestParameters)
			{
				arguments.Add("request." + parameter.PropertyName);
			}
		}

		if (plan.AppHasCancellationToken)
		{
			arguments.Add("context.CancellationToken");
		}

		var call = "_service." + method.Name + "(" + string.Join(", ", arguments) + ")";
		var asyncKeyword = plan.ResponseIsStream ? string.Empty : "async ";
		builder.AppendLine("	public " + asyncKeyword + plan.ContractReturnType + " " + plan.ContractMethodName + "(" + plan.ContractParameter + ")");
		builder.AppendLine("	{");
		if (plan.ResponseIsStream)
		{
			builder.AppendLine("		return " + call + ";");
		}
		else if (plan.IsVoid)
		{
			builder.AppendLine("		await " + call + ";");
			builder.AppendLine("		return global::Nerosoft.Euonia.Endpoint.EndpointEmpty.Instance;");
		}
		else
		{
			builder.AppendLine("		return await " + call + ";");
		}
		builder.AppendLine("	}");
	}

	private static void EmitRegistration(StringBuilder builder, List<(string Contract, string Adapter, string ServiceName, string ServiceType)> contracts)
	{
		builder.AppendLine("internal static class GrpcMappings");
		builder.AppendLine("{");
		builder.AppendLine("	internal static Type[] ServiceContracts => new[]");
		builder.AppendLine("	{");
		foreach (var contract in contracts.GroupBy(item => item.Contract).Select(group => group.First()))
		{
			builder.AppendLine("		typeof(" + contract.Contract + "),");
		}
		builder.AppendLine("	};");
		builder.AppendLine();
		builder.AppendLine("	public static void AddGenerated(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
		builder.AppendLine("	{");
		foreach (var contract in contracts.GroupBy(item => item.Adapter).Select(group => group.First()))
		{
			builder.AppendLine("		services.AddScoped<" + contract.Adapter + ">();");
		}
		builder.AppendLine("	}");
		builder.AppendLine();
		builder.AppendLine("	public static void MapGenerated(global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints)");
		builder.AppendLine("	{");
		builder.AppendLine("		var options = endpoints.ServiceProvider.GetService<global::Microsoft.Extensions.Options.IOptions<global::Nerosoft.Euonia.Endpoint.Grpc.GrpcExposureOptions>>()?.Value ?? new global::Nerosoft.Euonia.Endpoint.Grpc.GrpcExposureOptions();");
		builder.AppendLine("		var isService = endpoints.ServiceProvider.GetService<global::Microsoft.Extensions.DependencyInjection.IServiceProviderIsService>();");
		builder.AppendLine("		var logger = endpoints.ServiceProvider.GetService<global::Microsoft.Extensions.Logging.ILoggerFactory>()?.CreateLogger(\"Nerosoft.Euonia.Endpoint.Grpc\");");
		foreach (var contract in contracts.GroupBy(item => item.Adapter).Select(group => group.First()))
		{
			builder.AppendLine("		if (isService?.IsService(typeof(" + contract.ServiceType + ")) == false)");
			builder.AppendLine("		{");
			builder.AppendLine("			if (options.ThrowOnUnregisteredService) throw new global::System.InvalidOperationException(\"gRPC service '" + contract.ServiceType + "' is not registered.\");");
			builder.AppendLine("			logger?.LogWarning(\"gRPC service '" + contract.ServiceType + "' is not registered; endpoint skipped.\");");
			builder.AppendLine("		}");
			builder.AppendLine("		else");
			builder.AppendLine("		{");
			builder.AppendLine("			var metadata = endpoints.ServiceProvider.GetService<global::Nerosoft.Euonia.Endpoint.Grpc.GrpcMetadataRegistry>()?.GetServiceMetadata(typeof(" + contract.ServiceType + "));");
			builder.AppendLine("			var builder = endpoints.MapGrpcService<" + contract.Adapter + ">();");
			builder.AppendLine("			if (metadata is { Count: > 0 }) builder.WithMetadata(metadata.ToArray());");
			builder.AppendLine("			if (options.RequireAuthorization) builder.RequireAuthorization();");
			builder.AppendLine("		}");
		}
		builder.AppendLine("	}");
		builder.AppendLine("}");
	}

	private static MethodPlan? BuildPlan(INamedTypeSymbol serviceType, Entry entry, string contractName)
	{
		var method = entry.Method;
		if (method.Parameters.Any(parameter => IsCallContext(parameter.Type)))
		{
			return null;
		}

		if (method.Parameters.Any(parameter => parameter.HasExplicitDefaultValue && !IsCancellationToken(parameter.Type)))
		{
			return null;
		}

		var parameters = method.Parameters.Where(parameter => !IsCancellationToken(parameter.Type) && !IsCallContext(parameter.Type)).ToArray();
		var streamParameters = parameters.Where(parameter => IsAsyncEnumerable(parameter.Type)).ToArray();
		if (streamParameters.Length > 1)
		{
			return null;
		}

		var streamParameter = streamParameters.FirstOrDefault();
		if (streamParameter != null && parameters.Length != 1)
		{
			return null;
		}

		var returnType = method.ReturnType;
		var responseIsStream = IsAsyncEnumerable(returnType);
		var (isTask, taskResult) = GetTaskResult(returnType);
		if (!responseIsStream && !isTask)
		{
			return null;
		}

		var isVoid = !responseIsStream && taskResult == null;
		var responseType = responseIsStream
			? GetGenericArgument(returnType)!
			: taskResult ?? "global::Nerosoft.Euonia.Endpoint.EndpointEmpty";

		var appHasCancellationToken = method.Parameters.Any(parameter => IsCancellationToken(parameter.Type));
		var requestParameters = new List<ParameterInfo>();
		string? requestWrapperName = null;
		string requestType;
		var requestIsStream = streamParameter != null;

		if (requestIsStream)
		{
			requestType = "global::System.Collections.Generic.IAsyncEnumerable<" + GetGenericArgument(streamParameter!.Type) + ">";
		}
		else if (parameters.Length == 0)
		{
			requestType = "global::Nerosoft.Euonia.Endpoint.EndpointEmpty";
		}
		else
		{
			requestWrapperName = contractName + "_" + Sanitize(entry.Route) + "Request";
			for (var i = 0; i < parameters.Length; i++)
			{
				requestParameters.Add(new ParameterInfo(
					"global::" + parameters[i].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", string.Empty),
					ToPascal(parameters[i].Name)));
			}
			requestType = requestWrapperName;
		}

		var contractMethodName = Sanitize(entry.Route);
		if (!contractMethodName.EndsWith("Async", StringComparison.Ordinal))
		{
			contractMethodName += "Async";
		}

		var contractReturnType = responseIsStream
			? "global::System.Collections.Generic.IAsyncEnumerable<" + responseType + ">"
			: "global::System.Threading.Tasks.Task<" + responseType + ">";

		var contractParameter = requestIsStream
			? requestType + " request, global::ProtoBuf.Grpc.CallContext context = default"
			: (requestWrapperName == null
				? "global::Nerosoft.Euonia.Endpoint.EndpointEmpty request, global::ProtoBuf.Grpc.CallContext context = default"
				: requestType + " request, global::ProtoBuf.Grpc.CallContext context = default");

		return new MethodPlan
		{
			Method = method,
			Route = entry.Route,
			ContractMethodName = contractMethodName,
			ContractReturnType = contractReturnType,
			ContractParameter = contractParameter,
			RequestType = requestType,
			RequestWrapperName = requestWrapperName,
			RequestParameters = requestParameters,
			RequestIsStream = requestIsStream,
			ResponseIsStream = responseIsStream,
			IsVoid = isVoid,
			AppHasCancellationToken = appHasCancellationToken
		};
	}

	private static int GetMethodKind(AttributeData attribute)
	{
		foreach (var argument in attribute.NamedArguments)
		{
			if (argument.Key == "Method" && argument.Value.Value is int value)
			{
				return value;
			}
		}

		return 0;
	}

	private static bool IsMethodKindCompatible(Entry entry)
	{
		var method = entry.Method;
		var parameters = method.Parameters.Where(parameter => !IsCancellationToken(parameter.Type) && !IsCallContext(parameter.Type)).ToArray();
		var requestIsStream = parameters.Any(parameter => IsAsyncEnumerable(parameter.Type));
		var responseIsStream = IsAsyncEnumerable(method.ReturnType);
		var expected = requestIsStream
			? (responseIsStream ? 3 : 2)
			: (responseIsStream ? 1 : 0);
		return entry.MethodKind == expected;
	}

	private static bool IsExposeGrpcAttribute(AttributeData attribute)
	{
		return attribute.AttributeClass?.ToDisplayString() == AttributeName;
	}

	private static string GetString(AttributeData attribute, string name)
	{
		foreach (var argument in attribute.NamedArguments)
		{
			if (argument.Key == name && argument.Value.Value is string value)
			{
				return value;
			}
		}
		return string.Empty;
	}

	private static string GetDefaultServiceName(INamedTypeSymbol type)
	{
		var name = type.Name;
		if (name.Length > 1 && name[0] == 'I' && char.IsUpper(name[1]))
		{
			name = name.Substring(1);
		}
		foreach (var suffix in new[] { "ApplicationService", "AppService", "Service" })
		{
			if (name.Length > suffix.Length && name.EndsWith(suffix, StringComparison.Ordinal))
			{
				name = name.Substring(0, name.Length - suffix.Length);
				break;
			}
		}
		return name;
	}

	private static string GetDefaultMethodName(IMethodSymbol method)
	{
		var name = method.Name;
		if (name.Length > 5 && name.EndsWith("Async", StringComparison.Ordinal))
		{
			name = name.Substring(0, name.Length - 5);
		}
		return name;
	}

	private static bool IsCancellationToken(ITypeSymbol type)
	{
		return type.ToDisplayString() == "System.Threading.CancellationToken";
	}

	private static bool IsCallContext(ITypeSymbol type)
	{
		return type.ToDisplayString() == "ProtoBuf.Grpc.CallContext";
	}

	private static bool IsAsyncEnumerable(ITypeSymbol type)
	{
		return type is INamedTypeSymbol named
			&& named.IsGenericType
			&& named.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.IAsyncEnumerable<T>";
	}

	private static (bool IsTask, string? ResultType) GetTaskResult(ITypeSymbol type)
	{
		if (type is INamedTypeSymbol named && named.IsGenericType)
		{
			var definition = named.OriginalDefinition.ToDisplayString();
			if (definition == "System.Threading.Tasks.Task<TResult>" || definition == "System.Threading.Tasks.ValueTask<TResult>")
			{
				return (true, named.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
			}
		}

		if (type.ToDisplayString() == "System.Threading.Tasks.Task" || type.ToDisplayString() == "System.Threading.Tasks.ValueTask")
		{
			return (true, null);
		}

		return (false, null);
	}

	private static string? GetGenericArgument(ITypeSymbol type)
	{
		return type is INamedTypeSymbol named && named.TypeArguments.Length == 1
			? named.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
			: null;
	}

	private static string ToPascal(string name)
	{
		if (string.IsNullOrEmpty(name))
		{
			return "Value";
		}
		return char.ToUpperInvariant(name[0]) + name.Substring(1);
	}

	private static string Sanitize(string value)
	{
		var builder = new StringBuilder(value.Length + 1);
		foreach (var character in value)
		{
			builder.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
		}
		if (builder.Length == 0)
		{
			builder.Append("Endpoint");
		}
		if (char.IsDigit(builder[0]))
		{
			builder.Insert(0, '_');
		}
		return builder.ToString();
	}

	private sealed class Entry
	{
		public Entry(IMethodSymbol method, string prefix, string route, int methodKind)
		{
			Method = method;
			Prefix = prefix;
			Route = route;
			MethodKind = methodKind;
		}

		public IMethodSymbol Method { get; }
		public string Prefix { get; }
		public string Route { get; }
		public int MethodKind { get; }
	}

	private sealed class MethodPlan
	{
		public IMethodSymbol Method { get; set; } = null!;
		public string Route { get; set; } = string.Empty;
		public string ContractMethodName { get; set; } = string.Empty;
		public string ContractReturnType { get; set; } = string.Empty;
		public string ContractParameter { get; set; } = string.Empty;
		public string RequestType { get; set; } = string.Empty;
		public string? RequestWrapperName { get; set; }
		public List<ParameterInfo> RequestParameters { get; set; } = new();
		public bool RequestIsStream { get; set; }
		public bool ResponseIsStream { get; set; }
		public bool IsVoid { get; set; }
		public bool AppHasCancellationToken { get; set; }
	}

	private sealed class ParameterInfo
	{
		public ParameterInfo(string type, string propertyName)
		{
			Type = type;
			PropertyName = propertyName;
		}

		public string Type { get; }
		public string PropertyName { get; }
	}
}
