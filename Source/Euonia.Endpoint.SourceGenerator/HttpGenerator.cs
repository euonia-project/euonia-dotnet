using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Nerosoft.Euonia.Endpoint.SourceGenerator;

/// <summary>
/// 为 <c>ExposeWebApiAttribute</c> 生成强类型 Minimal API 映射。
/// </summary>
[Generator]
public sealed class HttpGenerator : IIncrementalGenerator
{
	private const string AttributeName = "Nerosoft.Euonia.Endpoint.ExposeWebApiAttribute";

	/// <inheritdoc/>
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var methods = context.SyntaxProvider.ForAttributeWithMetadataName(
				AttributeName,
				static (node, _) => node is MethodDeclarationSyntax,
				static (ctx, _) => (IMethodSymbol)ctx.TargetSymbol)
			.Where(static method => method.ContainingType is { TypeKind: TypeKind.Interface })
			.Collect();

		var hasRuntimeReference = context.CompilationProvider.Select(static (compilation, _) =>
			compilation.ReferencedAssemblyNames.Any(assembly => assembly.Name == "Euonia.Endpoint.Http"));

		context.RegisterSourceOutput(methods.Combine(hasRuntimeReference), static (production, source) =>
			Execute(production, source.Left, source.Right));
	}

	private static void Execute(SourceProductionContext context, ImmutableArray<IMethodSymbol> methods, bool hasRuntimeReference)
	{
		if (!hasRuntimeReference)
		{
			return;
		}

		if (methods.IsDefaultOrEmpty)
		{
			return;
		}

		var builder = new StringBuilder();
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine("using System;");
		builder.AppendLine("using System.Threading;");
		builder.AppendLine("using System.Threading.Tasks;");
		builder.AppendLine("using Microsoft.AspNetCore.Http;");
		builder.AppendLine("using Microsoft.AspNetCore.Mvc;");
		builder.AppendLine("using Microsoft.AspNetCore.Routing;");
		builder.AppendLine();
		builder.AppendLine("[assembly: global::Nerosoft.Euonia.Endpoint.Http.HttpGeneratedMapping(typeof(global::Nerosoft.Euonia.Endpoint.Generated.HttpMappings))]");
		builder.AppendLine();
		builder.AppendLine("namespace Nerosoft.Euonia.Endpoint.Generated;");
		builder.AppendLine();
		builder.AppendLine("internal static class HttpMappings");
		builder.AppendLine("{");
		builder.AppendLine("	public static void MapGenerated(global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints)");
		builder.AppendLine("	{");

		foreach (var method in methods)
		{
			var serviceType = method.ContainingType;
			if (serviceType == null || serviceType.IsGenericType)
			{
				continue;
			}

			foreach (var attribute in method.GetAttributes().Where(IsAttribute))
			{
				var plan = BuildPlan(method);
				if (plan == null)
				{
					continue;
				}

				var prefix = GetString(attribute, "Prefix");
				var route = GetString(attribute, "Route");
				var httpMethods = GetMethods(attribute);
				builder.AppendLine("		global::Nerosoft.Euonia.Endpoint.Http.HttpGeneratedMapper.Map(");
				builder.AppendLine("			endpoints,");
				builder.AppendLine("			typeof(" + serviceType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "),");
				builder.AppendLine("			nameof(" + serviceType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "." + method.Name + "),");
				builder.AppendLine("			" + Quote(prefix) + ",");
				builder.AppendLine("			" + Quote(route) + ",");
				builder.AppendLine("			new[] { " + string.Join(", ", httpMethods.Select(Quote)) + " },");
				var parameterTypes = method.Parameters
					.Select(parameter => "typeof(" + parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")")
					.ToArray();
				builder.AppendLine(parameterTypes.Length == 0
					? "			   global::System.Array.Empty<global::System.Type>(),"
					: "			   new[] { " + string.Join(", ", parameterTypes) + " },");
				builder.AppendLine("			" + plan.Lambda + ");");
			}
		}

		builder.AppendLine("	}");
		builder.AppendLine("}");
		context.AddSource("HttpGenerated.g.cs", builder.ToString());
	}

	private static HttpPlan? BuildPlan(IMethodSymbol method)
	{
		if (method.IsStatic || method.IsGenericMethod || method.ReturnsByRef || method.ReturnType.IsRefLikeType)
		{
			return null;
		}

		var parameters = method.Parameters;
		foreach (var parameter in parameters)
		{
			if (parameter.RefKind != RefKind.None || parameter.IsParams)
			{
				return null;
			}

			if (parameter.HasExplicitDefaultValue && !IsCancellationToken(parameter.Type))
			{
				return null;
			}
		}

		var returnType = method.ReturnType;
		if (IsAsyncEnumerable(returnType))
		{
			return null;
		}

		foreach (var parameter in parameters)
		{
			if (IsUnsupportedParameter(parameter.Type))
			{
				return null;
			}
		}

		var bodyParameters = parameters.Where(parameter => !IsSimpleType(parameter.Type) && !IsCancellationToken(parameter.Type)).ToArray();
		if (bodyParameters.Length > 1)
		{
			return null;
		}

		var bodyParameter = bodyParameters.FirstOrDefault();
		var taskReturn = IsTask(returnType, out var isVoid, out var resultType);
		if (taskReturn && resultType != null && IsAsyncEnumerableName(resultType))
		{
			return null;
		}

		if (bodyParameter != null && !taskReturn)
		{
			return null;
		}

		var parameterTexts = new List<string>();
		var argumentTexts = new List<string>();
		foreach (var parameter in parameters)
		{
			if (bodyParameter != null && SymbolEqualityComparer.Default.Equals(parameter, bodyParameter))
			{
				argumentTexts.Add("__body!");
				continue;
			}

			var typeName = parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
			var fromQuery = IsSimpleCollection(parameter.Type) ? "[global::Microsoft.AspNetCore.Mvc.FromQuery] " : string.Empty;
			var parameterName = GetSafeParameterName(parameter.Name);
			parameterTexts.Add(fromQuery + typeName + " @" + parameterName);
			argumentTexts.Add("@" + parameterName);
		}

		if (bodyParameter != null)
		{
			parameterTexts.Add("global::Microsoft.AspNetCore.Http.HttpContext __http");
		}

		var serviceType = method.ContainingType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
		parameterTexts.Add("[global::Microsoft.AspNetCore.Mvc.FromServices] " + serviceType + " __service");

		var call = "__service." + method.Name + "(" + string.Join(", ", argumentTexts) + ")";
		var bodyType = bodyParameter?.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
		var bodyRequired = bodyParameter?.NullableAnnotation != NullableAnnotation.Annotated;
		var bodyRead = bodyParameter == null
			? null
			: "var __bodyResult = await global::Nerosoft.Euonia.Endpoint.Http.HttpGeneratedMapper.ReadBodyAsync<" + bodyType + ">(__http, " + (bodyRequired ? "true" : "false") + ");"
			  + " if (!__bodyResult.Succeeded) { return global::Microsoft.AspNetCore.Http.Results.Problem(statusCode: 400, title: \"Invalid request parameter\", detail: \"Invalid or missing request body.\"); }"
			  + " var __body = __bodyResult.Value;";

		string lambda;
		if (taskReturn)
		{
			var statements = new List<string>();
			if (bodyRead != null)
			{
				statements.Add(bodyRead);
			}

			if (isVoid)
			{
				statements.Add("await " + call + ";");
				statements.Add("return global::Microsoft.AspNetCore.Http.Results.NoContent();");
			}
			else if (IsResult(resultType))
			{
				statements.Add("return await " + call + ";");
			}
			else
			{
				statements.Add("return global::Microsoft.AspNetCore.Http.Results.Ok(await " + call + ");");
			}

			lambda = "async (" + string.Join(", ", parameterTexts) + ") => { " + string.Join(" ", statements) + " }";
		}
		else if (IsResult(returnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)))
		{
			lambda = "(" + string.Join(", ", parameterTexts) + ") => " + call;
		}
		else
		{
			lambda = "(" + string.Join(", ", parameterTexts) + ") => global::Microsoft.AspNetCore.Http.Results.Ok(" + call + ")";
		}

		return new HttpPlan(lambda);
	}

	private static bool IsTask(ITypeSymbol type, out bool isVoid, out string? resultType)
	{
		isVoid = false;
		resultType = null;
		if (type.ToDisplayString() == "System.Threading.Tasks.Task" || type.ToDisplayString() == "System.Threading.Tasks.ValueTask")
		{
			isVoid = true;
			return true;
		}

		if (type is INamedTypeSymbol named && named.IsGenericType)
		{
			var definition = named.OriginalDefinition.ToDisplayString();
			if (definition == "System.Threading.Tasks.Task<TResult>" || definition == "System.Threading.Tasks.ValueTask<TResult>")
			{
				resultType = named.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
				return true;
			}
		}

		return false;
	}

	private static bool IsCancellationToken(ITypeSymbol type)
	{
		return type.ToDisplayString() == "System.Threading.CancellationToken";
	}

	private static bool IsUnsupportedParameter(ITypeSymbol type)
	{
		var name = type.ToDisplayString();
		return name == "Microsoft.AspNetCore.Http.HttpContext"
			|| name == "Microsoft.AspNetCore.Http.HttpRequest"
			|| name == "Microsoft.AspNetCore.Http.HttpResponse"
			|| name == "Microsoft.AspNetCore.Http.IFormFile"
			|| name == "Microsoft.AspNetCore.Http.IFormFileCollection"
			|| name == "System.Security.Claims.ClaimsPrincipal"
			|| name == "System.IO.Stream"
			|| name == "System.IO.Pipelines.PipeReader"
			|| type.IsRefLikeType
			|| IsAsyncEnumerable(type);
	}

	private static bool IsAsyncEnumerable(ITypeSymbol type)
	{
		return type is INamedTypeSymbol named
			&& named.IsGenericType
			&& named.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.IAsyncEnumerable<T>";
	}

	private static bool IsAsyncEnumerableName(string type)
	{
		return type.StartsWith("global::System.Collections.Generic.IAsyncEnumerable<", StringComparison.Ordinal);
	}

	private static bool IsResult(string? type)
	{
		return type == "global::Microsoft.AspNetCore.Http.IResult";
	}

	private static string GetSafeParameterName(string name)
	{
		return name.StartsWith("__", StringComparison.Ordinal) ? "__p" + name : name;
	}

	private static bool IsSimpleCollection(ITypeSymbol type)
	{
		if (type is IArrayTypeSymbol array)
		{
			return array.ElementType.SpecialType != SpecialType.System_Byte && IsSimpleType(array.ElementType);
		}

		if (type is not INamedTypeSymbol named || !named.IsGenericType)
		{
			return false;
		}

		var definition = named.OriginalDefinition.ToDisplayString();
		return (definition is "System.Collections.Generic.IEnumerable<T>"
			        or "System.Collections.Generic.ICollection<T>"
			        or "System.Collections.Generic.IList<T>"
			        or "System.Collections.Generic.IReadOnlyCollection<T>"
			        or "System.Collections.Generic.IReadOnlyList<T>"
			        or "System.Collections.Generic.List<T>"
			        or "System.Collections.Generic.HashSet<T>"
			        or "System.Collections.Generic.ISet<T>"
			        or "System.Collections.Generic.IReadOnlySet<T>")
		       && IsSimpleType(named.TypeArguments[0]);
	}

	private static bool IsSimpleType(ITypeSymbol type)
	{
		if (IsCancellationToken(type))
		{
			return true;
		}

		if (type is IArrayTypeSymbol array)
		{
			return array.ElementType.SpecialType != SpecialType.System_Byte && IsSimpleType(array.ElementType);
		}

		if (type.SpecialType != SpecialType.None || type.TypeKind == TypeKind.Enum)
		{
			return type.SpecialType != SpecialType.System_Object;
		}

		var name = type.ToDisplayString();
		return name == "System.Guid"
			|| name == "System.DateTime"
			|| name == "System.DateTimeOffset"
			|| name == "System.TimeSpan"
			|| name == "System.DateOnly"
			|| name == "System.TimeOnly"
			|| name == "System.Uri";
	}

	private static bool IsAttribute(AttributeData attribute)
	{
		return attribute.AttributeClass?.ToDisplayString() == AttributeName;
	}

	private static string GetString(AttributeData attribute, string name)
	{
		foreach (var argument in attribute.NamedArguments)
		{
			if (argument.Key == name && argument.Value.Value is string value)
			{
				return value;
			}
		}
		return string.Empty;
	}

	private static IReadOnlyList<string> GetMethods(AttributeData attribute)
	{
		foreach (var argument in attribute.NamedArguments)
		{
			if (argument.Key != "Method" || argument.Value.Kind != TypedConstantKind.Array)
			{
				continue;
			}

			var values = argument.Value.Values
				.Where(value => value.Value is string)
				.Select(value => (string)value.Value!)
				.ToArray();
			if (values.Length > 0)
			{
				return values;
			}
		}

		return new[] { "POST" };
	}

	private static string Quote(string value)
	{
		return Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);
	}

	private sealed class HttpPlan
	{
		public HttpPlan(string lambda)
		{
			Lambda = lambda;
		}

		public string Lambda { get; }
	}
}
